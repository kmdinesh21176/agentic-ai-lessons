from langchain_ollama import ChatOllama
from langchain_core.tools import tool

# 1. Initialize your local Llama 3.2 model via Ollama with zero creativity for precise tool usage
llm = ChatOllama(model="llama3.2", temperature=0)

# 2. Turn a standard Python function into a tool using the @tool decorator.
# The docstring and type hints tell the LLM what the tool does and what arguments it needs.
@tool
def multiply(a: int, b: int) -> int:
    """Multiply two numbers together and return the result."""
    return a * b

# 3. Group our tools into a list
tools = [multiply]

# 4. Bind the tools to the LLM so it knows they are available to call
llm_with_tools = llm.bind_tools(tools)

# 5. Create a dictionary to map string tool names to actual executable Python functions
tool_map = {
    "multiply": multiply
}

# 6. Define the user prompt requiring math
user_prompt = "Can you calculate 1425 multiplied by 389? Use your tool."

# 7. Send the prompt to the model; it returns a response object with tool requests instead of plain text
response = llm_with_tools.invoke(user_prompt)

# 8. Print the raw tool request structure generated by the LLM
print("--- Step A: LLM Requested Tool ---")
print(response.tool_calls)

# 9. Check if the LLM actually requested any tools
if response.tool_calls:
    # Loop through each tool call requested by the model (in case it asks for multiple)
    for tool_call in response.tool_calls:
        
        # Extract the name of the tool the model wants to use (e.g., "multiply")
        tool_name = tool_call["name"]
        
        # Extract the dictionary of arguments the model generated (e.g., {'b': 389, 'a': 1425})
        tool_args = tool_call["args"]
        
        print(f"\n--- Step B: Executing Python Function '{tool_name}' ---")
        print(f"Arguments passed: {tool_args}")
        
        # Look up the function in our dictionary using the string name
        selected_tool = tool_map[tool_name]
        
        # Execute the function by passing the arguments dictionary into it
        tool_result = selected_tool.invoke(tool_args)
        
        # Print the final calculation result computed by Python
        print(f"Tool Output: {tool_result}")